"""Generates core/src/periph/svd.rs (register tables) from ST's STM32WB55_CM4.svd.

The SVD is taken from the pinned firmware tag (scripts/debug/STM32WB55_CM4.svd in
flipperzero-firmware 1.5.1; fetch the tree into firmware/cache/src/). Only hardware facts are
extracted: register names, offsets, reset values and which bits are readable/writable.

usage: python3 scripts/gen-svd-tables.py <STM32WB55_CM4.svd> > core/src/periph/svd.rs
"""
import sys
import xml.etree.ElementTree as ET

root = ET.parse(sys.argv[1]).getroot()
version = root.findtext("version")
peripherals = {p.findtext("name"): p for p in root.find("peripherals")}


def num(s):
    return int(s, 0) if s else 0


def masks(reg, default_access):
    access = reg.findtext("access") or default_access
    fields = reg.find("fields")
    size = num(reg.findtext("size")) or 32
    full = (1 << size) - 1
    if fields is None or len(fields) == 0:
        r = full if access in ("read-only", "read-write") else 0
        w = full if access in ("write-only", "read-write") else 0
        return r, w
    r = w = 0
    for f in fields:
        off = num(f.findtext("bitOffset"))
        width = num(f.findtext("bitWidth"))
        m = ((1 << width) - 1) << off
        fa = f.findtext("access") or access
        if fa in ("read-only", "read-write"):
            r |= m
        if fa in ("write-only", "read-write"):
            w |= m
    return r, w


def registers(p):
    base = p.get("derivedFrom")
    regs = p.find("registers")
    if regs is None and base:
        regs = peripherals[base].find("registers")
    out = []
    for reg in regs:
        r, w = masks(reg, "read-write")
        out.append((reg.findtext("name"), num(reg.findtext("addressOffset")), num(reg.findtext("resetValue")), r, w))
    return sorted(out, key=lambda x: x[1])


print("// SPDX-License-Identifier: GPL-3.0-or-later")
print("// @generated by scripts/gen-svd-tables.py — do not edit.")
print(f"// Source: ST STM32WB55_CM4.svd v{version} (flipperzero-firmware 1.5.1, scripts/debug/).")
print("// Hardware facts only: register offsets, reset values, readable/writable bit masks.")
print()
print("use super::regfile::{PeriphDesc, RegDesc};")
print()
names = []
for name in sorted(peripherals, key=lambda n: num(peripherals[n].findtext("baseAddress"))):
    p = peripherals[name]
    ident = name.upper()
    names.append(ident)
    print(f"pub const {ident}: PeriphDesc = PeriphDesc {{")
    print(f'    name: "{name}",')
    print(f"    base: 0x{num(p.findtext('baseAddress')):08X},")
    print("    regs: &[")
    for rn, off, reset, r, w in registers(p):
        print(f'        RegDesc {{ name: "{rn}", offset: 0x{off:03X}, reset: 0x{reset:08X}, read: 0x{r:08X}, write: 0x{w:08X} }},')
    print("    ],")
    print("};")
    print()
print(f"pub const ALL: &[PeriphDesc] = &[{', '.join(names)}];")
